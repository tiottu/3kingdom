// 나라마다 옷 색깔
const NATION_COLORS = {
  '촉나라': ['#3fa34d', '#2e7d4f', '#58b368', '#1e8449', '#7dbb52'],
  '위나라': ['#2c4f8c', '#3b7dd8', '#34495e', '#5d6d7e', '#1f618d'],
  '오나라': ['#c0392b', '#e67e22', '#d35400', '#e74c3c', '#a93226'],
  etc: ['#8e44ad', '#b8860b', '#7d4f8f', '#16a085', '#6e4b2a']
};
const SKINS = ['#ffdcb8', '#ffe2c4', '#f5d0ad', '#f2c9a0', '#e8b48c'];

// 이길 때마다 WIN_UNLOCK 순서대로 친구가 된다 (촉, 위, 오, 그 밖을 번갈아)
const WIN_UNLOCK = [];
const winGroups = {};
MORE_GENERALS.forEach(([id, name, nation, hat, beard, stats, skill, intro, extra], i) => {
  const pal = NATION_COLORS[nation] || NATION_COLORS.etc;
  const bun = hat === 'bun';
  GENERALS[id] = Object.assign({
    name, nation, hat, beard, skill, intro,
    face: bun ? '#ffe6d0' : SKINS[i % SKINS.length],
    hatColor: bun ? '#2d2d2d' : pal[(i + 2) % pal.length],
    armor: bun ? ['#f78fb3', '#a29bfe', '#74b9ff', '#fab1a0', '#55efc4'][i % 5] : pal[i % pal.length]
  }, extra || {});
  STATS[id] = stats;
  const key = NATION_COLORS[nation] ? nation : 'etc';
  (winGroups[key] = winGroups[key] || []).push(id);
});
for (let i = 0; WIN_UNLOCK.length < MORE_GENERALS.length; i++) {
  for (const list of Object.values(winGroups)) if (list[i]) WIN_UNLOCK.push(list[i]);
}
